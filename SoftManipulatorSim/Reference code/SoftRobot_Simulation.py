# Scene inputs -> math                       [bridge: Blender UI -> Part A inputs]
# -----------------------------------------------------------------------------
# Converts the panel sliders into the exact argument form the MATLAB kinematics
# expect. Note the convention from Example_SoftManipulator_model.m: theta is
# passed as deg2rad(theta_deg)/2 (the panel shows the physical bend in degrees,
# halved here), while phi and beta are just deg2rad. reset_to_matlab_example
# restores the fixed example pose from that same MATLAB script.
def get_inputs_from_scene(scene):
    theta = [math.radians(scene.sr_theta1_deg) / 2.0, math.radians(scene.sr_theta2_deg) / 2.0]
    phi = [math.radians(scene.sr_phi1_deg), math.radians(scene.sr_phi2_deg)]
    beta = [math.radians(scene.sr_beta1_deg), math.radians(scene.sr_beta2_deg)]
    robot_params = {"L": [scene.sr_L1, scene.sr_L2]}
    T_home = [0, 0, 0, 0, 0, 0]
    return theta, phi, beta, robot_params, T_home, scene.sr_sensor_L


def compute_scene_robot(scene):
    theta, phi, beta, robot_params, T_home, sensor_L = get_inputs_from_scene(scene)
    return compute_backbone(theta=theta, phi=phi, beta=beta, robot_params=robot_params,
                            T_home=T_home, sensor_L=sensor_L,
                            n_points_per_segment=scene.sr_points_per_segment)

