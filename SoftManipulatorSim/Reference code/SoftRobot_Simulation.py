# -----------------------------------------------------------------------------
# End effector          [MATLAB port: show_SoftManipulator.m red sensor line
#                        + Blender-only orange cone tip]
# -----------------------------------------------------------------------------
# In show_SoftManipulator.m the tip is drawn as a single thick red line from the
# last backbone point to T (the sensor transform): line(...,'Color','r',
# 'LineWidth',4). We reproduce that as the red shaft here. The orange cone is a
# Blender-only addition: it marks the tip position AND points along the tip's
# local Z, so you can see which way the end effector is facing.
def update_end_effector(T, TF, scene):
    tip = np.asarray(T[0:3, 3], dtype=float)
    tip_z = np.asarray(T[0:3, 2], dtype=float)
    nrm = np.linalg.norm(tip_z)
    if nrm > 1e-9:
        tip_z = tip_z / nrm
    last_disk = np.asarray(TF[-1][0:3, 3], dtype=float)

    if np.linalg.norm(tip - last_disk) > 1e-6:
        shaft = make_cylinder_between(EE_SHAFT_NAME, last_disk, tip, radius=max(scene.sr_radius * 0.35, 0.2))
        if shaft:
            assign_color(shaft, "SR_EE_red", (0.9, 0.08, 0.08, 1.0))
    else:
        delete_by_prefix(EE_SHAFT_NAME)

    cone = make_cone_along(EE_TIP_NAME, tip, tip_z,
                           length=max(scene.sr_radius * 2.2, 6.0),
                           radius=max(scene.sr_radius * 0.9, 0.5))
    if cone:
        assign_color(cone, "SR_EE_orange", (1.0, 0.45, 0.0, 1.0))


# -----------------------------------------------------------------------------
# TARGET SIMULATION              [Blender only; target positions use FwdSRM.m]
# -----------------------------------------------------------------------------
# Targets are green spheres placed at reachable points in the workspace. The
# researcher steers the tip to a target; reaching it (within a tolerance)
# registers it and a new target is placed. Positions come from forward
# kinematics on a random valid joint configuration, so every target is
# guaranteed reachable. When an obstacle is enabled, target points that fall
# inside the obstacle are rejected so the task stays feasible.
def random_reachable_tip(scene, avoid_obstacle=True, max_tries=25):
    """Sample a random valid joint config and return its tip (always reachable).

    If an obstacle is active, resample up to `max_tries` times to avoid placing
    a target inside the obstacle volume (so the target is not unreachable
    without contact). Falls back to the last sample if all attempts fail.
    """
    tip = None
    for _ in range(max_tries):
        th = [math.radians(random.uniform(0.0, 90.0)) / 2.0 for _ in range(2)]
        ph = [math.radians(random.uniform(-180.0, 180.0)) for _ in range(2)]
        bt = [math.radians(random.uniform(-45.0, 45.0)) for _ in range(2)]
        T, _ = fwd_srm(th, ph, bt, {"L": [scene.sr_L1, scene.sr_L2]},
                       T_home=[0, 0, 0, 0, 0, 0], sensor_L=scene.sr_sensor_L)
        tip = np.asarray(T[0:3, 3], dtype=float)
        if not (avoid_obstacle and scene.sr_obstacle_active):
            return tip
        # Keep the target clear of the obstacle by at least the target's own radius.
        if not point_in_obstacle(tip, scene, extra=scene.sr_target_radius):
            return tip
    return tip


def update_targets(T, scene, in_contact):
    """Keep `target count` targets alive; register any the tip reaches; redraw.

    `in_contact` is True when the robot body is currently intersecting the
    obstacle. If "target needs clear path" is on, a target is only registered
    while the body is clear -- this is what forces maneuvering AROUND the
    obstacle rather than pushing through it.
    """
    while len(_targets) < scene.sr_target_count:
        _targets.append(random_reachable_tip(scene))
    while len(_targets) > scene.sr_target_count:
        _targets.pop()

    tip = np.asarray(T[0:3, 3], dtype=float)
    blocked = in_contact and scene.sr_require_clearance
    for i in range(len(_targets)):
        if np.linalg.norm(tip - _targets[i]) <= scene.sr_target_tolerance:
            if blocked:
                # Tip is at the target but the body is inside the obstacle:
                # do not register this reach; the path was not clear.
                continue
            _targets[i] = random_reachable_tip(scene)
            scene.sr_target_score += 1
            print(f"[sim] target reached; total reached = {scene.sr_target_score}")

    delete_by_prefix(TARGET_PREFIX)
    for i, pos in enumerate(_targets):
        assign_color(make_sphere(f"{TARGET_PREFIX}{i}", pos, scene.sr_target_radius),
                     "SR_target_mat", (0.1, 0.9, 0.2, 1.0))


# -----------------------------------------------------------------------------
# OBSTACLE COURSE                                                  [Blender only]
# -----------------------------------------------------------------------------
# An optional cylinder or cuboid the robot must be steered around. We model it
# analytically (an upright primitive aligned with world Z) and test the robot's
# backbone points against that volume. The obstacle is inflated by the robot's
# own tube radius plus a clearance margin, so "contact" means the visible tube
# would touch the visible obstacle, not just the infinitely-thin centreline.
#
# Assumptions (documented so results are interpretable):
#   - the obstacle is axis-aligned and upright (no tilt);
#   - `radius` is the cylinder radius, or the cuboid half-width in X and Y;
#   - `height` is the full extent along Z, centred on obstacle z.
def point_in_obstacle(p, scene, extra=0.0):
    """True if point `p` lies inside the obstacle volume, expanded by `extra`."""
    ox, oy, oz = scene.sr_obstacle_x, scene.sr_obstacle_y, scene.sr_obstacle_z
    radius = scene.sr_obstacle_radius
    half_h = scene.sr_obstacle_height / 2.0
    dz = abs(float(p[2]) - oz)
    if dz > half_h + extra:
        return False
    if scene.sr_obstacle_shape == "CYLINDER":
        dxy = math.hypot(float(p[0]) - ox, float(p[1]) - oy)
        return dxy <= radius + extra
    # CUBOID
    return abs(float(p[0]) - ox) <= radius + extra and abs(float(p[1]) - oy) <= radius + extra


def backbone_contacts_obstacle(points, scene):
    """Vectorized test: does ANY backbone point lie inside the obstacle volume,
    inflated by (robot tube radius + clearance)? Returns a bool."""
    if not scene.sr_obstacle_active:
        return False
    ox, oy, oz = scene.sr_obstacle_x, scene.sr_obstacle_y, scene.sr_obstacle_z
    radius = scene.sr_obstacle_radius
    half_h = scene.sr_obstacle_height / 2.0
    margin = scene.sr_radius + scene.sr_obstacle_clearance  # tube half-thickness + safety gap
    pts = np.asarray(points, dtype=float)
    dz = np.abs(pts[:, 2] - oz)
    within_z = dz <= half_h + margin
    if scene.sr_obstacle_shape == "CYLINDER":
        dxy = np.hypot(pts[:, 0] - ox, pts[:, 1] - oy)
        inside = within_z & (dxy <= radius + margin)
    else:  # CUBOID
        inside = (within_z
                  & (np.abs(pts[:, 0] - ox) <= radius + margin)
                  & (np.abs(pts[:, 1] - oy) <= radius + margin))
    return bool(np.any(inside))


def update_obstacle(scene, in_contact):
    """Create/update the obstacle object at its configured pose and shape, and
    color it grey when clear or amber while the body is in contact.

    If the shape enum changed since last time, the old object is removed first
    so the correct primitive (cylinder vs box) is rebuilt."""
    shape = scene.sr_obstacle_shape
    center = (scene.sr_obstacle_x, scene.sr_obstacle_y, scene.sr_obstacle_z)
    radius = scene.sr_obstacle_radius
    height = scene.sr_obstacle_height

    existing = bpy.data.objects.get(OBSTACLE_NAME)
    if existing is not None and existing.get("sr_shape", "") != shape:
        bpy.data.objects.remove(existing, do_unlink=True)

    if shape == "CYLINDER":
        obj = make_upright_cylinder(OBSTACLE_NAME, center, radius, height)
    else:  # CUBOID: full dims are (2*half-width, 2*half-width, height)
        obj = make_box(OBSTACLE_NAME, center, (radius * 2.0, radius * 2.0, height))
    obj["sr_shape"] = shape  # remember which primitive we built

    if in_contact:
        assign_color(obj, "SR_obstacle_contact", (0.95, 0.55, 0.1, 1.0))  # amber
    else:
        assign_color(obj, "SR_obstacle_clear", (0.5, 0.5, 0.55, 1.0))     # neutral grey
    return obj


# -----------------------------------------------------------------------------
# Main update                                                     [Blender only]
# -----------------------------------------------------------------------------
# Called on every change (button, key, mouse move, or the live timer). It runs
# the Part A kinematics for the current scene inputs, then refreshes every
# visual: the robot tube, the debug frames, the end-effector, the obstacle, and
# the targets. Everything downstream reads from the same points/T/TF so the
# picture is always self-consistent.
def update_soft_robot(context=None):
    scene = bpy.context.scene if context is None else context.scene
    points, T, TF = compute_scene_robot(scene)

    obj = get_or_create_curve_object(scene, len(points))
    update_curve_points(obj, points)

    update_frames(TF) if scene.sr_show_frames else delete_by_prefix(FRAME_OBJECT_PREFIX)

    if scene.sr_show_end_effector:
        update_end_effector(T, TF, scene)
    else:
        delete_by_prefix(EE_SHAFT_NAME)
        delete_by_prefix(EE_TIP_NAME)

    # --- Obstacle course: test the body against the obstacle, then draw it. ---
    in_contact = backbone_contacts_obstacle(points, scene)
    if scene.sr_obstacle_active:
        update_obstacle(scene, in_contact)
        # Count a "contact event" only on the rising edge (clear -> contact),
        # not every frame the body stays inside, so the tally is meaningful.
        was_in_contact = bool(scene.get("_sr_was_in_contact", False))
        if in_contact and not was_in_contact:
            scene.sr_contact_count += 1
            print(f"[sim] body entered obstacle volume; contact events = {scene.sr_contact_count}")
        scene["_sr_was_in_contact"] = in_contact
    else:
        delete_by_prefix(OBSTACLE_NAME)
        scene["_sr_was_in_contact"] = False

    # --- Targets: reaching one requires a clear path when the obstacle is on. ---
    if scene.sr_target_sim_active:
        update_targets(T, scene, in_contact)
    else:
        delete_by_prefix(TARGET_PREFIX)
        _targets.clear()

    obj["tip_x"], obj["tip_y"], obj["tip_z"] = float(T[0, 3]), float(T[1, 3]), float(T[2, 3])
    return obj


def live_update_timer():
    if bpy.context.scene.sr_live_update:
        update_soft_robot()
        return TIMER_INTERVAL_SECONDS
    return None


