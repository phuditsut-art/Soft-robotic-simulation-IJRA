class SR_OT_MouseControl(bpy.types.Operator):
    """Move the mouse (no button held) to bend the active segment."""
    bl_idname = "soft_robot.mouse_control"
    bl_label = "Start Mouse Control"
    bl_description = "Move mouse to bend (L/R=phi, U/D=theta); wheel=twist; 1/2 select; R reset; Esc stop"

    def execute(self, context):
        context.scene.sr_mouse_control = True
        context.window_manager.modal_handler_add(self)
        self.report({"INFO"}, "Mouse control on: move to bend, wheel=twist, 1/2 select, R reset, Esc stop")
        return {"RUNNING_MODAL"}

    def modal(self, context, event):
        scene = context.scene
        if not scene.sr_mouse_control:
            return {"CANCELLED"}
        if event.type == "ESC":
            scene.sr_mouse_control = False
            self.report({"INFO"}, "Mouse control stopped")
            return {"CANCELLED"}
        if handle_common_keys(scene, event, context):
            return {"RUNNING_MODAL"}

        theta_name, phi_name, beta_name = active_segment_props(scene)

        if event.value == "PRESS" and event.type == "WHEELUPMOUSE":
            setattr(scene, beta_name, getattr(scene, beta_name) + scene.sr_twist_step)
            update_soft_robot(context)
            return {"RUNNING_MODAL"}
        if event.value == "PRESS" and event.type == "WHEELDOWNMOUSE":
            setattr(scene, beta_name, getattr(scene, beta_name) - scene.sr_twist_step)
            update_soft_robot(context)
            return {"RUNNING_MODAL"}

        # Move-to-bend: any mouse motion bends the active segment (no button needed).
        if event.type == "MOUSEMOVE":
            dx = event.mouse_x - event.mouse_prev_x
            dy = event.mouse_y - event.mouse_prev_y
            if dx == 0 and dy == 0:
                return {"PASS_THROUGH"}
            sens = scene.sr_mouse_sensitivity
            new_phi = ((getattr(scene, phi_name) + dx * sens + 180.0) % 360.0) - 180.0
            setattr(scene, phi_name, new_phi)
            setattr(scene, theta_name, max(0.0, min(180.0, getattr(scene, theta_name) + dy * sens)))
            update_soft_robot(context)
            return {"PASS_THROUGH"}

        return {"PASS_THROUGH"}


