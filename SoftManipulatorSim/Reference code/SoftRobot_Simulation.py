def active_segment_props(scene):
    """Return the (theta, phi, beta) property names for the active segment."""
    if scene.sr_active_segment == "1":
        return "sr_theta1_deg", "sr_phi1_deg", "sr_beta1_deg"
    return "sr_theta2_deg", "sr_phi2_deg", "sr_beta2_deg"


def mesh_get_or_add(name, add_fn):
    """Return an object by name, creating it via add_fn() if it doesn't exist yet."""
    obj = bpy.data.objects.get(name)
    if obj is None:
        add_fn()
        obj = bpy.context.object
        obj.name = name
    return obj


def handle_common_keys(scene, event, context):
    """Essential keys used during mouse control: 1/2 select segment, R reset.

    Returns True if the event was consumed.
    """
    if event.value != "PRESS":
        return False
    if event.type in {"ONE", "NUMPAD_1"}:
        scene.sr_active_segment = "1"
        return True
    if event.type in {"TWO", "NUMPAD_2"}:
        scene.sr_active_segment = "2"
        return True
    if event.type == "R":
        reset_to_matlab_example(scene)
        update_soft_robot(context)
        return True
    return False


