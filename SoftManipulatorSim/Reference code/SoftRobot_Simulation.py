# -----------------------------------------------------------------------------
# DRAW ROBOT SEGMENTS      [Blender rendering of show_SoftManipulator.m output]
# -----------------------------------------------------------------------------
# MATLAB's show_SoftManipulator.m drew the backbone straight into a figure with
# line plots. Blender has no "plot" call, so instead we keep ONE persistent 3D
# object and just move its points each update (rather than deleting and
# rebuilding it every frame, which flickers and is slow).
#
# Blender newcomer note on the object we use:
#   - a "curve" is a path defined by control points;
#   - a "spline" is one such path inside the curve. We use a POLY spline, which
#     simply connects its points with straight lines (no smoothing) -- perfect,
#     because Part A already gives us many closely-spaced points along the arc;
#   - "bevel_depth" sweeps a circle along that path, turning the thin line into
#     a solid TUBE. In Blender bevel_depth is the tube RADIUS (not diameter).
def get_or_create_curve_object(scene, n_points):
    obj = bpy.data.objects.get(ROBOT_OBJECT_NAME)
    if obj is None:
        curve = bpy.data.curves.new(CURVE_NAME, type="CURVE")
        curve.dimensions = "3D"
        curve.resolution_u = 2
        curve.fill_mode = "FULL"
        curve.splines.new(type="POLY").points.add(n_points - 1)
        obj = bpy.data.objects.new(ROBOT_OBJECT_NAME, curve)
        bpy.context.collection.objects.link(obj) #actually visualizes the object in the scene

    curve = obj.data
    curve.bevel_depth = scene.sr_radius      # bevel_depth = sets tube RADIUS in Blender (derived from scene input)
    curve.bevel_resolution = 12
    if len(curve.splines) == 0:
        curve.splines.new(type="POLY").points.add(n_points - 1)
    spline = curve.splines[0]
    current = len(spline.points)
    if current < n_points:
        spline.points.add(n_points - current)
    elif current > n_points:                     # POLY can't drop points -> rebuild
        curve.splines.clear()
        curve.splines.new(type="POLY").points.add(n_points - 1)
    return obj


def update_curve_points(obj, points):
    for p, xyz in zip(obj.data.splines[0].points, points):
        p.co = (float(xyz[0]), float(xyz[1]), float(xyz[2]), 1.0)


# -----------------------------------------------------------------------------
# Mesh shape helpers (cylinders, cones, spheres, boxes)            [Blender only]
# -----------------------------------------------------------------------------
# These build the small solid shapes used for the coordinate frames, the
# end-effector, the targets, and the obstacle -- NOT the robot body (that is the
# beveled spline above). Each helper follows the same recipe:
#   1. create-or-reuse a named object (via mesh_get_or_add), then
#   2. reposition/resize it in place on every later call.
# Blender newcomer note: Blender makes cylinders/cones standing up along their
# own local +Z. `to_track_quat("Z","Y")` builds the rotation that aims that
# local Z along whatever direction vector we computed, so a shape can lie
# between two arbitrary points. Setting `obj.dimensions` resizes via the
# bounding box (diameter x diameter x length), which is why radius is doubled.
def assign_color(obj, mat_name, rgba):
    mat = bpy.data.materials.get(mat_name)
    if mat is None:
        mat = bpy.data.materials.new(mat_name)
        mat.diffuse_color = rgba
    if obj.data.materials:
        obj.data.materials[0] = mat
    else:
        obj.data.materials.append(mat)


def make_cylinder_between(name, start, end, radius=0.25):
    start, end = Vector(start), Vector(end)
    direction = end - start
    length = direction.length
    if length < 1e-9:
        return None
    mid = (start + end) / 2.0
    obj = mesh_get_or_add(name, lambda: bpy.ops.mesh.primitive_cylinder_add(
        vertices=12, radius=radius, depth=length, location=mid))
    obj.location = mid
    obj.dimensions = (radius * 2.0, radius * 2.0, length)
    obj.rotation_euler = direction.to_track_quat("Z", "Y").to_euler()
    return obj


def make_cone_along(name, base, direction, length, radius):
    base, d = Vector(base), Vector(direction)
    if d.length < 1e-9 or length < 1e-9:
        return None
    d = d.normalized()
    center = base + d * (length / 2.0)
    obj = mesh_get_or_add(name, lambda: bpy.ops.mesh.primitive_cone_add(
        vertices=16, radius1=radius, radius2=0.0, depth=length, location=center))
    obj.location = center
    obj.dimensions = (radius * 2.0, radius * 2.0, length)
    obj.rotation_euler = d.to_track_quat("Z", "Y").to_euler()
    return obj


def make_sphere(name, pos, radius):
    loc = (float(pos[0]), float(pos[1]), float(pos[2]))
    obj = mesh_get_or_add(name, lambda: bpy.ops.mesh.primitive_uv_sphere_add(radius=radius, location=loc))
    obj.location = loc
    obj.dimensions = (radius * 2.0, radius * 2.0, radius * 2.0)
    return obj


def make_upright_cylinder(name, center, radius, height):
    """A cylinder standing along world Z, centred at `center`. Used for the
    cylindrical obstacle. No rotation is needed because it stays upright."""
    cx, cy, cz = float(center[0]), float(center[1]), float(center[2])
    obj = mesh_get_or_add(name, lambda: bpy.ops.mesh.primitive_cylinder_add(
        vertices=24, radius=radius, depth=height, location=(cx, cy, cz)))
    obj.location = (cx, cy, cz)
    obj.dimensions = (radius * 2.0, radius * 2.0, height)
    obj.rotation_euler = (0.0, 0.0, 0.0)
    return obj


def make_box(name, center, size):
    """An axis-aligned box centred at `center` with full dimensions `size`
    (sx, sy, sz). Used for the cuboidal obstacle. primitive_cube_add makes a
    unit cube; setting `dimensions` then stretches it to the requested size."""
    cx, cy, cz = float(center[0]), float(center[1]), float(center[2])
    obj = mesh_get_or_add(name, lambda: bpy.ops.mesh.primitive_cube_add(
        size=1.0, location=(cx, cy, cz)))
    obj.location = (cx, cy, cz)
    obj.dimensions = (float(size[0]), float(size[1]), float(size[2]))
    obj.rotation_euler = (0.0, 0.0, 0.0)
    return obj


def delete_by_prefix(prefix):
    for obj in list(bpy.context.scene.objects):
        if obj.name.startswith(prefix):
            bpy.data.objects.remove(obj, do_unlink=True)


