from __future__ import annotations

# =============================================================================
# SOFT MANIPULATOR KINEMATICS  ->  BLENDER LIVE VISUALISER  + TARGET SIMULATION
# =============================================================================
#
# Python/Blender port of the MATLAB "New Soft Manipulator Kinematics" package.
# Models a 2 segment soft robot.
# Each segment: theta (bend angle / xi), phi (bend-plane orientation), beta (twist about local z), L (length).
#
# Derived from these MATLAB files:
#   transxyz.m, rx/ry/rz.m, rx_rad/ry_rad/rz_rad.m, rod_T.m, rod_T_twist.m,
#   FwdSRM.m, show_SoftManipulator.m, CoorPlot.m, Example_SoftManipulator_model.m
#
# CONTROLS (in the 3D viewport, after "Start Mouse Control"):
#   move mouse        -> bend active segment (left/right = phi, up/down = theta)
#   scroll wheel      -> twist (beta) of active segment
#   keys 1 / 2        -> choose which segment you are editing
#   R                 -> reset to the MATLAB example
#   Esc               -> stop control
#
# TARGET SIMULATION: green sphere(s) appear at random reachable
# spots; the end-effector tip must reach one to register it, after which a new
# target is placed. Reachable points are generated by sampling a random valid
# joint configuration and running forward kinematics (the same workspace-sampling
# idea used in Example_SoftManipulator_model.m), so every target is reachable.
#
# OBSTACLE COURSE: an optional cylinder or cuboid can be placed in the workspace.
# The robot body must be steered AROUND it to reach the target. The simulation
# continuously tests the robot backbone against the obstacle volume and reports
# contact (this is a measurement/telemetry feature, not a scored arcade game):
#   - the obstacle turns amber while any part of the body is inside it,
#   - a running count of contact events is displayed,
#   - by default a target only registers as reached when the body is clear of
#     the obstacle (toggle "target needs clear path" to change this).
#
# -----------------------------------------------------------------------------
# HOW THIS FILE IS ORGANISED (and how to read the section tags):
#   PART A = pure kinematics, a direct port of the MATLAB .m files. No Blender.
#   PART B = everything that talks to Blender (drawing, UI, mouse control, etc).
# Inside PART B each section is tagged so you can see its origin:
#   [MATLAB port: xxx.m] = draws/computes something defined in that .m file
#   [Blender only]       = pure Blender plumbing with no MATLAB equivalent
#                          (MATLAB drew straight to a figure; Blender instead
#                           needs persistent 3D objects, materials, operators)
# =============================================================================

